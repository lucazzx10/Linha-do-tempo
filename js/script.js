const grid = document.querySelector("#essayGrid");
const search = document.querySelector("#searchInput");
const filter = document.querySelector("#categoryFilter");
const count = document.querySelector("#totalCount");
const empty = document.querySelector("#emptyState");
const dialog = document.querySelector("#essayDialog");
let activeEssay = 0;

function renderEssays() {
  const term = search.value.toLocaleLowerCase("pt-BR").trim();
  const category = filter.value;
  const filtered = essays.filter(e => (category === "Todas" || e.category === category) &&
    (e.title + " " + e.theme + " " + e.category).toLocaleLowerCase("pt-BR").includes(term));
  count.textContent = filtered.length;
  empty.hidden = filtered.length !== 0;
  grid.innerHTML = filtered.map(e => `<article class="essay-card"><div class="essay-card-top"><span class="essay-number">${String(e.id).padStart(2,"0")}</span><span class="essay-category">${e.category}</span></div><h3>${e.title}</h3><p>${e.theme}</p><button class="essay-open" data-id="${e.id}" type="button">Ler redação <span>↗</span></button></article>`).join("");
  grid.querySelectorAll("button").forEach(btn => btn.addEventListener("click", () => openEssay(Number(btn.dataset.id)-1)));
}
function openEssay(index) {
  activeEssay = index;
  const e = essays[index];
  document.querySelector("#dialogCategory").textContent = e.category.toUpperCase();
  document.querySelector("#dialogNumber").textContent = String(e.id).padStart(2,"0");
  document.querySelector("#dialogTitle").textContent = e.title;
  document.querySelector("#dialogTheme").textContent = e.theme;
  document.querySelector("#dialogText").textContent = e.text;
  if (!dialog.open) dialog.showModal();
}
document.querySelector("#closeDialog").addEventListener("click", () => dialog.close());
document.querySelector("#nextEssay").addEventListener("click", () => openEssay((activeEssay+1)%essays.length));
dialog.addEventListener("click", e => { if(e.target === dialog) dialog.close(); });
search.addEventListener("input", renderEssays);
filter.addEventListener("change", renderEssays);
renderEssays();

